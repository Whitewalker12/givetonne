/**
 * Compiles the Solidity sources with solc-js and writes typed ABI + bytecode
 * modules (checked in, so the app never needs solc at runtime).
 *
 *   contracts/GiveTonneRetirements.sol  → src/lib/chain/GiveTonneRetirements.ts
 *   contracts/testing/FakeToucan.sol    → scripts/generated/FakeToucan.ts (tests only)
 *
 *   npm run chain:compile
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
// eslint-disable-next-line @typescript-eslint/no-require-imports
const solc = require("solc");

const root = path.resolve(__dirname, "..");

type Artifact = { abi: unknown; evm: { bytecode: { object: string } } };

function compile(file: string): Record<string, Artifact> {
  const source = readFileSync(path.join(root, file), "utf8");
  const input = {
    language: "Solidity",
    sources: { [file]: { content: source } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      evmVersion: "paris", // no PUSH0: works on every EVM chain and local dev nodes
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
    },
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (output.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
  if (errors.length) {
    for (const e of errors) console.error(e.formattedMessage);
    process.exit(1);
  }
  return output.contracts[file];
}

function emit(out: string, contracts: Record<string, Artifact>) {
  const body = Object.entries(contracts)
    .map(
      ([name, c]) =>
        `export const ${name} = {\n  abi: ${JSON.stringify(c.abi, null, 2)} as const,\n  bytecode: "0x${c.evm.bytecode.object}" as const,\n};`,
    )
    .join("\n\n");
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(path.join(root, out), `// Generated by scripts/compile-contract.ts — do not edit.\n${body}\n`);
  const bytes = Object.values(contracts).reduce((n, c) => n + c.evm.bytecode.object.length / 2, 0);
  console.log(`Wrote ${out} (${Object.keys(contracts).join(", ")}; ${bytes} bytes)`);
}

const main = compile("contracts/GiveTonneRetirements.sol").GiveTonneRetirements;
writeFileSync(
  path.join(root, "src/lib/chain/GiveTonneRetirements.ts"),
  `// Generated by scripts/compile-contract.ts — do not edit.\nexport const abi = ${JSON.stringify(main.abi, null, 2)} as const;\nexport const bytecode = "0x${main.evm.bytecode.object}" as const;\n`,
);
console.log(`Wrote src/lib/chain/GiveTonneRetirements.ts (${main.evm.bytecode.object.length / 2} bytes)`);

emit("scripts/generated/FakeToucan.ts", compile("contracts/testing/FakeToucan.sol"));
