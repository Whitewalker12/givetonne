/**
 * Compiles contracts/GiveTonneRetirements.sol with solc-js and writes the ABI +
 * bytecode to src/lib/chain/GiveTonneRetirements.ts (checked in, so the app
 * never needs solc at runtime).
 *
 *   npm run chain:compile
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
// eslint-disable-next-line @typescript-eslint/no-require-imports
const solc = require("solc");

const root = path.resolve(__dirname, "..");
const source = readFileSync(path.join(root, "contracts/GiveTonneRetirements.sol"), "utf8");

const input = {
  language: "Solidity",
  sources: { "GiveTonneRetirements.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris", // no PUSH0: works on every EVM chain and local dev nodes
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

const c = output.contracts["GiveTonneRetirements.sol"].GiveTonneRetirements;
const out = path.join(root, "src/lib/chain/GiveTonneRetirements.ts");
writeFileSync(
  out,
  `// Generated by scripts/compile-contract.ts — do not edit.\nexport const abi = ${JSON.stringify(c.abi, null, 2)} as const;\nexport const bytecode = "0x${c.evm.bytecode.object}" as const;\n`,
);
console.log(`Wrote ${path.relative(root, out)} (${c.evm.bytecode.object.length / 2} bytes)`);
